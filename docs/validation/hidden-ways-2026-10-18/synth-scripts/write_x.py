#!/usr/bin/env python3
"""hidden-ways/file-x: write docs/AMENDMENTS-2026-10-18x.md (the APPLIED file) from draft-x.md and apply-x-run.json
(write_w.py's form). The items (draft-x.md from '## The items' to its end) are copied byte for byte. Usage: write_x.py ROOT"""
import json, sys
ROOT = sys.argv[1]
V = f'{ROOT}/docs/validation/hidden-ways-2026-10-18'
draft = open(f'{V}/draft-x.md', encoding='utf-8', newline='').read()
lines = draft.split('\n')
src = next(l for l in lines if l.startswith('**Sources.**'))
howto = next(l for l in lines if l.startswith('**How to read the items.**'))
i = draft.index('\n## The items\n') + 1
items = draft[i:]
run = json.load(open(f'{V}/apply-x-run.json', encoding='utf-8'))
assert run['live'] and run['failure'] is None and len(run['rows']) == 20 and all(r['ok'] == 'ok' for r in run['rows'])
assert all(x['newCount'] == 1 and x['oldOutsideNew'] == 0 for x in run['final'])
B, A, L = run['before'], run['after'], run['lines']
before_lines = {'docs/volumes/V13-world.md': 4832, 'docs/HOST-REQUIREMENTS-2026-10-18.md': 938,
                'docs/volumes/INDEX.md': 261, 'docs/volumes/SUMMARY.md': 245}
counts = {}
for r in run['rows']: counts[r['file']] = counts.get(r['file'], 0) + 1
def fmt(n): return f'{n:,}'.replace(',', ' ') if n >= 1000 else str(n)
order = ['docs/volumes/V13-world.md', 'docs/HOST-REQUIREMENTS-2026-10-18.md', 'docs/volumes/INDEX.md', 'docs/volumes/SUMMARY.md']
tt = '; '.join(f'`{f}` `{B[f]}` ({fmt(before_lines[f])}) → `{A[f]}` ({fmt(L[f])}), {counts[f]}' for f in order)
TITLE = ("# Amendments x — file w's figures carried into the totals, BCR-V13-37, the host document's milestone table and "
         "the owner's answer to Q5")
head = TITLE + f"""

> Written and applied on Opus 5.5 by the follow-up seat of the hidden-ways workflow on the owner's decision J421 ("i follow your recommendations", 2026-10-19 07:12Z), from the consistency confirm of file w as applied (`docs/validation/hidden-ways-2026-10-18/confirm-consistency.md`, F1–F6); lane hidden-ways/file-x

Numbered from **976** (file w ended at 975); items 976–982.

**APPLIED** by lane hidden-ways/file-x on 2026-10-19 on the owner's decision J421 (2026-10-19 07:12Z, verbatim: "i
follow your recommendations" — the answer to V13 §11 Q5: the price accepted, M-W2 8 → 10 pw with the staged row
37–45 → 39–47, and M-W2 named; the host's stand-in from `routeFacts`' stretches meanwhile; the trod record a product of
the simulator feed, not a canon slot) — the 20 fragments of items 976–982 applied in this file's order to four files
(`docs/volumes/V13-world.md` 5, `docs/HOST-REQUIREMENTS-2026-10-18.md` 3, `docs/volumes/INDEX.md` 4,
`docs/volumes/SUMMARY.md` 8; `docs/volumes/V14-sites.md` `1fcdce8e633db3b39322e3c3854cc99a` unchanged), each current
text matched exactly once in its target as it stood at its turn and each new text exactly once after, every new text
exactly once in its target at the end, no current text left outside its own new text, and, on copies first, the new
texts put back in reverse order restoring the targets byte for byte (by script, `python3 -I`:
`docs/validation/hidden-ways-2026-10-18/synth-scripts/check_x.py`, 407 checks, 0 failures, four negative controls
caught; `apply_x.py`, a dry run on copies first giving the same hashes); no fragment skipped, no adjustment to a
fragment's text. The bundle `docs/ARCHITECTURE-FULL.md` regenerated by `tools/bundle_architecture.py`, its `--check`
exiting 0.

**The application, target by target** (md5 before → after, lines as `wc -l` gives them, fragments; before = file w's
after-md5s, re-hashed by this lane before the first fragment): {tt}. The record of the run is
`docs/validation/hidden-ways-2026-10-18/file-x.md` (the table: id, file, line landed, ok) and its machine copy
`apply-x-run.json`; the draft `draft-x.md` and its machine copy `draft-x.fragments.json` are kept unchanged as the
record.

{src}

{howto} In this applied file, "as it stands now" in an item's locator and current-text label is the target as it stood
before this file (the md5s above); `file-x.md` gives the line each fragment landed at.

---

"""
body = head + items
open(f'{ROOT}/docs/AMENDMENTS-2026-10-18x.md', 'w', encoding='utf-8', newline='').write(body)
assert items in body and body.endswith(items)
print('written', body.count('\n'), 'lines')
