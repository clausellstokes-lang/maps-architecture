#!/usr/bin/env python3
"""hidden-ways/apply: write docs/AMENDMENTS-2026-10-18w.md (the APPLIED file) from draft-w.md and apply-run.json.
The items (draft-w.md from '## The items' to its end) are copied byte for byte."""
import json, sys
ROOT = sys.argv[1]
V = f'{ROOT}/docs/validation/hidden-ways-2026-10-18'
draft = open(f'{V}/draft-w.md', encoding='utf-8', newline='').read()
lines = draft.split('\n')
src = lines[8]; howto = lines[10]
assert src.startswith('**Sources.**') and howto.startswith('**How to read the items.**')
i = draft.index('\n## The items\n') + 1
items = draft[i:]
run = json.load(open(f'{V}/apply-run.json', encoding='utf-8'))
assert run['live'] and run['failure'] is None and len(run['rows']) == 114 and all(r['ok'] == 'ok' for r in run['rows'])
B, A, L = run['before'], run['after'], run['lines']
before_lines = {'docs/volumes/V13-world.md': 4611, 'docs/volumes/V14-sites.md': 3340,
                'docs/HOST-REQUIREMENTS-2026-10-18.md': 935, 'docs/volumes/INDEX.md': 260, 'docs/volumes/SUMMARY.md': 228}
counts = {}
for r in run['rows']: counts[r['file']] = counts.get(r['file'], 0) + 1
def fmt(n): return f'{n:,}'.replace(',', ' ') if n >= 1000 else str(n)
order = ['docs/volumes/V13-world.md', 'docs/volumes/V14-sites.md', 'docs/HOST-REQUIREMENTS-2026-10-18.md',
         'docs/volumes/INDEX.md', 'docs/volumes/SUMMARY.md']
tt = '; '.join(f'`{f}` `{B[f]}` ({fmt(before_lines[f])}) → `{A[f]}` ({fmt(L[f])}), {counts[f]}' for f in order)
head = f"""# Amendments w — the hidden ways: the host side's request of 2026-10-18 and the map's answer

> Designed by the hidden-ways workflow (J407) under the owner's delegation (J404: "Decisions and judgment to you"); revised by the correction run (J415) and for the owner's word of 2026-10-19 (J416); answered by the owner on 2026-10-19 (J421) and applied on Opus 5.5 by the apply workflow (J422); lane hidden-ways/apply

Numbered from **955** (file v ended at 954); items 955–975.

**APPLIED** by lane hidden-ways/apply on 2026-10-19 on the owner's decision J421 (2026-10-19 07:12Z, verbatim: "i
follow your recommendations" — the answer to V13 §11 Q5, item 966 (c): the price accepted, M-W2 8 → 10 pw with the
staged row 39–47, and M-W2 named as the milestone that carries the trods, their reveal and the junction ends; the host's
bodies chain builds its stand-in cover graph from `routeFacts`' stretches meanwhile and retires it when the trod record
lands; the trod record reaches the host as the simulator feed's third optional product, not a canon slot) — the 114
fragments of items 955–975 applied in this file's order to five files (`docs/volumes/V13-world.md` 83,
`docs/volumes/V14-sites.md` 6, `docs/HOST-REQUIREMENTS-2026-10-18.md` 12, `docs/volumes/INDEX.md` 7,
`docs/volumes/SUMMARY.md` 6), each current text matched exactly once in its target as it stood at its turn and each new
text exactly once after, every new text exactly once in its target at the end, no current text left outside its own
new text, and the new texts put back in reverse order restoring the five targets byte for byte (by script, `python3 -I`:
`docs/validation/hidden-ways-2026-10-18/synth-scripts/apply_w.py`, a dry run on copies first giving the same hashes);
no fragment skipped. The bundle `docs/ARCHITECTURE-FULL.md` was not regenerated by this lane (its `--check` reports it
stale after the application; left for the managing session, see *For the session* below).

**The application, target by target** (md5 before → after, lines as `wc -l` gives them, fragments; before = the
fragments' stated md5s, re-hashed by this lane before the first fragment): {tt}. The expected after-md5s were
recomputed by applying to copies first: V13's is `81b3a003…`, not fix-2's `a276c57f…`, because the answer seat
(`answer.md`) added J421's sentence to item 966 (c)'s new text; the other four as fix-2 and the answer seat's
`check_json.py` run gave them. The record of the run is `docs/validation/hidden-ways-2026-10-18/apply.md` (the table:
id, file, line landed, ok) and its machine copy `apply-run.json`; the draft `draft-w.md` and its machine copy
`draft-w.fragments.json` are kept unchanged as the record.

{src}

{howto} In this applied file, "as it stands now" in an item's locator and current-text label is the target as it stood
before this file (the md5s above); `apply.md` gives the line each fragment landed at.

---

"""
tail = f"""
---

## For the session (not items)

Found by the answer seat (`answer.md` §4) and confirmed live after the application; not edited here, because this lane
applies the items as the draft holds them: four applied new texts still speak of V13 §11 Q5 as open, which the owner's
answer J421 closes (file r item 926 and file v item 954 are the precedent: an owner's answer supersedes every live
sentence that says the question waits) —
- 965 (a), J-V13.116 (`docs/volumes/V13-world.md:4213`): "this reading of the door is put to the owner in Q5 (vetoable)";
- 968 (l) (`docs/HOST-REQUIREMENTS-2026-10-18.md:717`): "(V13 §11 Q5, open for the owner with the price and the bodies
  chain's order)";
- 969 (g), INDEX §6's V13 Q5 row (`docs/volumes/INDEX.md:225`): the row with "(recommended; vetoable)";
- 969 (k) (`docs/volumes/SUMMARY.md:173`): "the answer (file w, pending your look)".
A follow-up file (x) carrying J421 into these four sentences, as file v did for J398, is the managing session's call.
Also: `docs/ARCHITECTURE-FULL.md` wants regenerating by `tools/bundle_architecture.py` (`--check` reports STALE after
this file); the ledger wants J421's application row; `docs/PROGRESS.md` and `README.md` are not this lane's files.
"""
body = head + items.rstrip('\n') + '\n' + tail
open(f'{ROOT}/docs/AMENDMENTS-2026-10-18w.md', 'w', encoding='utf-8', newline='').write(body)
assert items in body
print('written', body.count('\n'), 'lines')
